const $ = (selector) => document.querySelector(selector);
const homeScreen = $("#home-screen");
const gameScreen = $("#game-screen");
const resultScreen = $("#result-screen");
const rulesDialog = $("#rules-dialog");

let sessionQuestions = [];
let currentIndex = 0;
let score = 0;
let correctAnswers = 0;
let wrongAnswers = 0;
let timeLeft = 15;
let timerId = null;
let answered = false;

function showScreen(screen) {
  [homeScreen, gameScreen, resultScreen].forEach(item => item.classList.add("hidden"));
  screen.classList.remove("hidden");
  window.scrollTo({ top: 0, behavior: "smooth" });
}

function shuffle(array) {
  const copy = [...array];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

function startGame() {
  clearInterval(timerId);
  sessionQuestions = shuffle(QUESTION_BANK).slice(0, 10);
  currentIndex = 0;
  score = 0;
  correctAnswers = 0;
  wrongAnswers = 0;
  $("#score").textContent = score;
  showScreen(gameScreen);
  renderQuestion();
}

function renderQuestion() {
  clearInterval(timerId);
  answered = false;
  timeLeft = 15;
  const item = sessionQuestions[currentIndex];
  $("#question-count").textContent = `${currentIndex + 1} / ${sessionQuestions.length}`;
  $("#question-number").textContent = `PERTANYAAN ${String(currentIndex + 1).padStart(2, "0")}`;
  $("#category-pill").textContent = item.category.toUpperCase();
  $("#question-text").textContent = item.question;
  $("#timer").textContent = timeLeft;
  $(".timer-card").classList.remove("warning");
  $("#progress-bar").style.width = `${(currentIndex / sessionQuestions.length) * 100}%`;
  $("#feedback").textContent = "";
  $("#feedback").className = "feedback";
  $("#next-btn").disabled = true;
  $("#next-btn").innerHTML = currentIndex === sessionQuestions.length - 1 ? 'Lihat hasil <span>✓</span>' : 'Soal berikutnya <span>→</span>';

  const list = $("#answer-list");
  list.innerHTML = "";
  item.options.forEach((option, index) => {
    const button = document.createElement("button");
    button.className = "answer-btn";
    button.type = "button";
    const letter = document.createElement("span");
    letter.className = "answer-letter";
    letter.textContent = String.fromCharCode(65 + index);
    const label = document.createElement("span");
    label.textContent = option;
    button.append(letter, label);
    button.addEventListener("click", () => chooseAnswer(index));
    list.appendChild(button);
  });
  timerId = setInterval(tick, 1000);
}

function tick() {
  timeLeft--;
  $("#timer").textContent = timeLeft;
  if (timeLeft <= 5) $(".timer-card").classList.add("warning");
  if (timeLeft <= 0) {
    clearInterval(timerId);
    chooseAnswer(-1);
  }
}

function chooseAnswer(selectedIndex) {
  if (answered) return;
  answered = true;
  clearInterval(timerId);
  const item = sessionQuestions[currentIndex];
  const buttons = [...document.querySelectorAll(".answer-btn")];
  buttons.forEach((button, index) => {
    button.disabled = true;
    if (index === item.answer) button.classList.add("correct");
    if (index === selectedIndex && selectedIndex !== item.answer) button.classList.add("incorrect");
  });

  const feedback = $("#feedback");
  if (selectedIndex === item.answer) {
    score += 10;
    correctAnswers++;
    $("#score").textContent = score;
    feedback.textContent = "✓ Tepat sekali! Kamu mendapat 10 poin.";
    feedback.classList.add("good");
  } else {
    wrongAnswers++;
    feedback.textContent = selectedIndex === -1
      ? `Waktu habis! Jawaban benar: ${item.options[item.answer]}.`
      : `Belum tepat. Jawaban benar: ${item.options[item.answer]}.`;
    feedback.classList.add("bad");
  }
  $("#progress-bar").style.width = `${((currentIndex + 1) / sessionQuestions.length) * 100}%`;
  $("#next-btn").disabled = false;
}

function nextQuestion() {
  if (!answered) return;
  if (currentIndex < sessionQuestions.length - 1) {
    currentIndex++;
    renderQuestion();
  } else {
    finishGame();
  }
}

function finishGame() {
  clearInterval(timerId);
  showScreen(resultScreen);
  $("#final-score").textContent = score;
  $("#correct-count").textContent = correctAnswers;
  $("#wrong-count").textContent = wrongAnswers;
  $("#accuracy").textContent = `${Math.round((correctAnswers / sessionQuestions.length) * 100)}%`;
  const title = correctAnswers >= 8 ? "Luar biasa, Master!" : correctAnswers >= 5 ? "Kerja bagus!" : "Terus berlatih!";
  $("#result-title").textContent = title;
  $("#result-subtitle").textContent = `Kamu menjawab ${correctAnswers} dari 10 pertanyaan dengan benar.`;
}

function quitGame() {
  clearInterval(timerId);
  if (window.confirm("Yakin ingin keluar? Progres permainan ini akan hilang.")) showScreen(homeScreen);
  else if (!answered) timerId = setInterval(tick, 1000);
}

$("#start-btn").addEventListener("click", startGame);
$("#next-btn").addEventListener("click", nextQuestion);
$("#quit-btn").addEventListener("click", quitGame);
$("#play-again-btn").addEventListener("click", startGame);
$("#home-btn").addEventListener("click", () => showScreen(homeScreen));
$("#rules-open").addEventListener("click", () => rulesDialog.showModal());
$("#rules-close").addEventListener("click", () => rulesDialog.close());
$("#rules-ok").addEventListener("click", () => rulesDialog.close());

